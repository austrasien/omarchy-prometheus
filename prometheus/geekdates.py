def _sysadmin(d: dt.date) -> bool:
    """Last Friday of July."""
    return d.month == 7 and d.weekday() == 4 and (d + dt.timedelta(days=7)).month == 8


def _square_root(d: dt.date) -> bool:
    """3/3/09, 4/4/16, 5/5/25...: month = day = square root of the year's last two digits."""
    return d.month == d.day and d.year % 100 == d.day * d.day


