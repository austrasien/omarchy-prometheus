_BY_DATE = {(m, d): (aid, name, desc, quip) for m, d, aid, name, desc, quip in FIXED}


def event_on(day: dt.date) -> tuple[str, str, str, str] | None:
    """The calendar achievement a day grants: (id, name, description, line), or None."""
    fixed = _BY_DATE.get((day.month, day.day))
    if fixed:
        return fixed
    for aid, rule, name, desc, quip in MOVING:
        if rule(day):
            return aid, name, desc, quip
    return None


def all_entries() -> list[tuple[str, str, str, str]]:
    return [(aid, name, desc, quip) for _, _, aid, name, desc, quip in FIXED] + \
           [(aid, name, desc, quip) for aid, _, name, desc, quip in MOVING]
